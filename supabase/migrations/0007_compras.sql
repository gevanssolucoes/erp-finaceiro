-- A esteira só anda para frente. Exceções: cancelar antes da entrega e desfazer a aprovação
-- (volta para cotação) enquanto a compra não foi finalizada.
create or replace function privado.compras_valida_etapa() returns trigger
language plpgsql set search_path = public as $$
declare
  ordem text[] := array['pedido', 'confirmado', 'cotacao', 'aprovado', 'comprado', 'entregue'];
  de int := array_position(ordem, old.status);
  para int := array_position(ordem, new.status);
begin
  if new.status = old.status then return new; end if;
  if old.status in ('cancelado', 'entregue') then
    raise exception 'Pedido de compra % já está %', old.numero, old.status;
  end if;
  if new.status = 'cancelado' then
    if old.status = 'comprado' and new.lancamento_id is not null then
      raise exception 'Compra finalizada: exclua o lançamento em contas a pagar antes de cancelar';
    end if;
    new.cancelado_em := coalesce(new.cancelado_em, now());
    return new;
  end if;
  if old.status = 'aprovado' and new.status = 'cotacao' then
    new.cotacao_id := null; new.aprovado_em := null; new.aprovado_por := null; new.valor_aprovado := null;
    new.acima_orcamento := false; new.justificativa := null;
    return new;
  end if;
  if para is null or para < de then
    raise exception 'A esteira de compras não volta de % para %', old.status, new.status;
  end if;
  if para >= 4 and (new.cotacao_id is null or new.valor_aprovado is null) then
    raise exception 'Aprove uma cotação antes de seguir';
  end if;
  if new.status = 'aprovado' and new.acima_orcamento and coalesce(trim(new.justificativa), '') = '' then
    raise exception 'Compra acima da verba do orçamento precisa de justificativa';
  end if;
  return new;
end $$;

create trigger trg_compras_valida_etapa before update of status on compras_pedidos
  for each row execute function privado.compras_valida_etapa();

-- Segurança: mesmo padrão das demais tabelas (empresa do usuário, papel que grava, prédio permitido)
do $$
declare t text;
begin
  foreach t in array array['compras_pedidos', 'compras_itens', 'compras_cotacoes', 'compras_cotacao_itens', 'compras_eventos'] loop
    execute format('alter table %I enable row level security', t);
    execute format('create policy %I on %I for all to authenticated using (empresa_id in (select privado.minhas_empresas())) with check (empresa_id in (select privado.minhas_empresas()))', t || '_por_empresa', t);
    execute format('create policy %I on %I as restrictive for insert to authenticated with check ((select privado.pode_editar(empresa_id)))', t || '_grava', t);
    execute format('create policy %I on %I as restrictive for update to authenticated using ((select privado.pode_editar(empresa_id)))', t || '_altera', t);
    execute format('create policy %I on %I as restrictive for delete to authenticated using ((select privado.pode_editar(empresa_id)))', t || '_apaga', t);
  end loop;
end $$;

create policy compras_pedidos_por_predio on compras_pedidos as restrictive for select to authenticated
  using (privado.predio_permitido(predio_id));
