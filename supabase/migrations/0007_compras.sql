-- Esteira de compras: pedido -> confirmação -> cotação -> aprovação (com verba do orçamento)
-- -> compra finalizada (gera contas a pagar) -> acompanhamento de entrega -> entrada no estoque.
-- Somente acrescenta estruturas; não apaga dados.

create table compras_pedidos (
  id                   uuid primary key default gen_random_uuid(),
  empresa_id           uuid not null references empresas(id) on delete cascade,
  predio_id            uuid references predios(id),
  numero               bigint generated by default as identity,
  titulo               text not null,
  solicitante          text,
  prioridade           text not null default 'normal' check (prioridade in ('baixa', 'normal', 'urgente')),
  conta_id             uuid not null references plano_contas(id),       -- conta do orçamento que paga a compra
  centro_custo_id      uuid references centros_custo(id),
  competencia          date not null check (extract(day from competencia) = 1),
  necessidade          date,                                            -- quando precisa do material
  observacao           text,
  status               text not null default 'pedido'
                       check (status in ('pedido', 'confirmado', 'cotacao', 'aprovado', 'comprado', 'entregue', 'cancelado')),
  -- confirmação
  confirmado_em        timestamptz,
  confirmado_por       text,
  -- aprovação da cotação (fotografia da verba no momento)
  cotacao_id           uuid,
  aprovado_em          timestamptz,
  aprovado_por         text,
  valor_aprovado       numeric(14,2),
  verba_versao_id      uuid references orcamento_versoes(id) on delete set null,
  verba_orcada         numeric(14,2),
  verba_realizada      numeric(14,2),
  verba_comprometida   numeric(14,2),
  verba_disponivel     numeric(14,2),
  acima_orcamento      boolean not null default false,
  justificativa        text,
  -- compra finalizada
  comprado_em          date,
  finalizado_por       text,
  lancamento_id        uuid references lancamentos(id) on delete set null,
  pedido_fornecedor    text,
  previsao_entrega     date,
  transportadora       text,
  rastreio             text,
  -- entrega
  entregue_em          date,
  -- cancelamento
  cancelado_em         timestamptz,
  motivo_cancelamento  text,
  criado_por           uuid default auth.uid(),
  criado_em            timestamptz not null default now(),
  unique (numero)
);

create table compras_itens (
  id             uuid primary key default gen_random_uuid(),
  empresa_id     uuid not null references empresas(id) on delete cascade,
  pedido_id      uuid not null references compras_pedidos(id) on delete cascade,
  ordem          int not null default 1,
  produto_id     uuid references produtos(id),     -- com produto de estoque, a entrega gera entrada no estoque
  descricao      text not null,
  unidade        text not null default 'UN',
  quantidade     numeric(14,4) not null check (quantidade > 0),
  valor_estimado numeric(14,4),                    -- preço unitário estimado no pedido
  qtd_recebida   numeric(14,4) not null default 0 check (qtd_recebida >= 0)
);

create table compras_cotacoes (
  id                 uuid primary key default gen_random_uuid(),
  empresa_id         uuid not null references empresas(id) on delete cascade,
  pedido_id          uuid not null references compras_pedidos(id) on delete cascade,
  parceiro_id        uuid references parceiros(id),
  fornecedor         text not null,
  frete              numeric(14,2) not null default 0,
  desconto           numeric(14,2) not null default 0,
  total              numeric(14,2) not null,          -- itens + frete - desconto
  prazos_dias        int[] not null default '{30}',   -- condição de pagamento: {0} à vista, {30,60,90} em 3x
  forma_pagamento    text,
  prazo_entrega_dias int,
  validade           date,
  observacao         text,
  criado_em          timestamptz not null default now()
);

create table compras_cotacao_itens (
  id             uuid primary key default gen_random_uuid(),
  empresa_id     uuid not null references empresas(id) on delete cascade,
  cotacao_id     uuid not null references compras_cotacoes(id) on delete cascade,
  item_id        uuid not null references compras_itens(id) on delete cascade,
  valor_unitario numeric(14,4) not null check (valor_unitario >= 0),
  unique (cotacao_id, item_id)
);

alter table compras_pedidos add constraint compras_pedidos_cotacao_fk
  foreign key (cotacao_id) references compras_cotacoes(id) on delete set null;

-- Histórico da esteira (quem fez o quê e quando, atualizações de entrega)
create table compras_eventos (
  id         uuid primary key default gen_random_uuid(),
  empresa_id uuid not null references empresas(id) on delete cascade,
  pedido_id  uuid not null references compras_pedidos(id) on delete cascade,
  etapa      text not null,
  descricao  text,
  usuario    text,
  criado_em  timestamptz not null default now()
);

-- Ligações com estoque, contas a pagar e cadastro de produtos
alter table estoque_movimentos add column if not exists compra_item_id uuid references compras_itens(id) on delete set null;
alter table produtos add column if not exists estoque_minimo numeric(14,4);
alter table lancamentos drop constraint if exists lancamentos_origem_check;
alter table lancamentos add constraint lancamentos_origem_check
  check (origem in ('manual', 'importacao', 'faturamento', 'taxa_cartao', 'apuracao', 'compra'));

create index if not exists idx_cp_emp_status on compras_pedidos (empresa_id, status);
create index if not exists idx_cp_predio on compras_pedidos (predio_id);
create index if not exists idx_cp_conta on compras_pedidos (conta_id);
create index if not exists idx_cp_centro on compras_pedidos (centro_custo_id);
create index if not exists idx_cp_cotacao on compras_pedidos (cotacao_id);
create index if not exists idx_cp_lanc on compras_pedidos (lancamento_id);
create index if not exists idx_cp_versao on compras_pedidos (verba_versao_id);
create index if not exists idx_ci_pedido on compras_itens (pedido_id);
create index if not exists idx_ci_produto on compras_itens (produto_id);
create index if not exists idx_cc_pedido on compras_cotacoes (pedido_id);
create index if not exists idx_cc_parceiro on compras_cotacoes (parceiro_id);
create index if not exists idx_cci_cotacao on compras_cotacao_itens (cotacao_id);
create index if not exists idx_cci_item on compras_cotacao_itens (item_id);
